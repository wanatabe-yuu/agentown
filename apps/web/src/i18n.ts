/**
 * Interface language. English strings are the keys; Vietnamese is a dictionary
 * on top, so anything not translated yet still reads in English. The language
 * follows the browser until the person picks one (kept in this browser only).
 */
export type Lang = "vi" | "en";

const KEY = "agentown.lang";

function initial(): Lang {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === "vi" || saved === "en") return saved;
  } catch {}
  return typeof navigator !== "undefined" && navigator.language?.toLowerCase().startsWith("vi") ? "vi" : "en";
}

export const lang: Lang = initial();

/** What the person picked: a language, or "auto" to follow the browser. */
export const langChoice: Lang | "auto" = (() => {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === "vi" || saved === "en") return saved;
  } catch {}
  return "auto";
})();

export function setLang(next: Lang | "auto") {
  try {
    if (next === "auto") localStorage.removeItem(KEY);
    else localStorage.setItem(KEY, next);
  } catch {}
  location.reload();
}

/** "Café language": the template language, named after what the template calls its world. */
export const languageLabel = (term?: string) => (term ? t("{term} language", { term: t(term) }) : t("Template language"));

/** Languages an organization can work in (its template language). */
export const LANGUAGES: Array<{ id: Lang; name: string }> = [
  { id: "en", name: "English" },
  { id: "vi", name: "Tiếng Việt" },
];

/** Translate; {name} placeholders are filled from vars. */
export function t(s: string, vars?: Record<string, string | number>): string {
  let out = lang === "vi" ? (VI[s] ?? s) : s;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}

